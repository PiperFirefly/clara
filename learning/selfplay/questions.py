def _bfs_dist(edges, n, a, b):
    adj = {i: [] for i in range(n)}
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
    seen = {a}
    frontier = [a]
    dist = 0
    while frontier:
        nxt = []
        for u in frontier:
            if u == b:
                return dist
            for v in adj[u]:
                if v not in seen:
                    seen.add(v)
                    nxt.append(v)
        frontier = nxt
        dist += 1
    return -1


def gen_graph():
    n = random.randint(5, 7)
    edges = set()
    for i in range(n):
        for j in range(i + 1, n):
            if random.random() < 0.35:
                edges.add((i, j))
    for i in range(n - 1):
        edges.add((i, i + 1))
    edge_str = ", ".join(f"{u}-{v}" for u, v in sorted(edges))
    if random.choice([True, False]):
        a = random.randint(0, n - 1)
        b = random.choice([x for x in range(n) if x != a])
        dist = _bfs_dist(edges, n, a, b)
        q = (f"Nodes 0..{n - 1} with undirected edges: {edge_str}. "
             f"What is the shortest path length (number of edges) from node {a} to node {b}?")
        return q, str(dist), "graph"
    node = random.randint(0, n - 1)
    deg = sum(1 for e in edges if node in e)
    q = f"Nodes 0..{n - 1} with undirected edges: {edge_str}. What is the degree of node {node}?"
    return q, str(deg), "graph"


def gen_recurrence():
    kind = random.choice(["linear", "fib", "geo"])
    n = random.randint(4, 8)
    if kind == "linear":
        a0 = random.randint(0, 3)
        k = random.randint(2, 5)
        seq = [a0]
        for _ in range(n):
            seq.append(seq[-1] * k + 1)
        q = f"A sequence is defined by a(0)={a0} and a(n) = {k}*a(n-1) + 1. What is a({n})?"
        return q, str(seq[n]), "recurrence"
    if kind == "fib":
        seq = [0, 1]
        while len(seq) <= n + 1:
            seq.append(seq[-1] + seq[-2])
        q = f"A Fibonacci-like sequence starts a(0)=0, a(1)=1, a(n)=a(n-1)+a(n-2). What is a({n})?"
        return q, str(seq[n]), "recurrence"
    a0 = random.randint(1, 3)
    r = random.randint(2, 3)
    q = f"A sequence has a(0)={a0} and each term is {r} times the previous term. What is a({n})?"
    return q, str(a0 * r ** n), "recurrence"


