# ─────────────────────────── helpers ───────────────────────────

def _r(lo, hi):
    return random.randint(lo, hi)


def _pick(xs):
    return random.choice(xs)


# ─────────────────────────── 1. arithmetic ───────────────────────────

def gen_arithmetic():
    a, b = _r(2, 24), _r(2, 24)
    op = _pick(["+", "-", "*"])
    if op == "+":
        ans = a + b
    elif op == "-":
        if a < b:
            a, b = b, a
        ans = a - b
    else:
        ans = a * b
    return f"Compute exactly, no steps: {a} {op} {b}", str(ans), "arithmetic"


