def _norm(s):
    if s is None:
        return ""
    return s.strip().lower().replace(",", "").replace("`", "").replace("'", "")


def parse_answer(text):
    """Pull a value + confidence out of a model's structured reply."""
    ans = None
    conf = None
    m = re.search(r"(?im)^\s*answer\s*:\s*(.+)$", text or "")
    if m:
        ans = m.group(1).strip()
    c = re.search(r"(?im)^\s*confidence\s*:\s*([0-9]*\.?[0-9]+)", text or "")
    if c:
        try:
            conf = float(c.group(1))
        except ValueError:
            conf = None
    if ans is None:
        ans = (text or "").strip()
    return ans, (conf if conf is not None else 0.5)


_WORD_KINDS = frozenset([
    "caesar", "anagram", "analogy", "truth_liar", "prisoner",
    "syllogism", "boolean", "calendar", "constraint",
])

# Leading articles / filler a lenient word-matcher should ignore when deciding
# whether the model restated the expected answer.
_ARTICLES = frozenset(["the", "a", "an", "it", "is", "that"])


def _tokens(s):
    """Lowercased word tokens (letters/digits only), articles stripped."""
    toks = re.findall(r"[a-z0-9]+", s)
    return [t for t in toks if t not in _ARTICLES]


def _word_match(a, e):
    """Lenient word-level match: expected's key tokens must appear in answer.

    Handles "The dog" vs "dog", "Carol owns the cat" vs "cat", "it is blue" vs
    "blue" — but NOT a genuinely different word ("Carol owns the cat" vs "dog"
    stays wrong, because the expected token is absent).
    """
    et = _tokens(e)
    if not et:
        return False
    at = _tokens(a)
    if not at:
        return False
    # all expected content tokens must show up somewhere in the answer
    for tok in et:
        if tok not in at:
            return False
    return True


def check_correct(answer_text, expected, kind=None):
    """Deterministic, kind-aware, LENIENT grade.

    The strict-equality failures from the overnight run were mostly the grader's
    fault: "The dog" vs "dog", "it is blue" vs "blue" were marked wrong purely
    on phrasing. This matcher is semantic/lenient: word kinds match on key-token
    presence, numeric kinds on extracted numbers, fractions via Fraction. It never
    marks a genuinely different answer correct (a missing expected token => False).
    """
    a = _norm(answer_text)
    e = _norm(expected)
    if not a:
        return False

    # matrix Nash — match the row,column cell, ignoring filler
    if kind == "matrix_nash":
        ac = re.findall(r"top|bottom", a)
        cc = re.findall(r"left|right", a)
        ec = re.findall(r"top|bottom", e)
        fc = re.findall(r"left|right", e)
        if not ec or not fc:
            return _word_match(a, e)
        return bool(ac and cc and ac[0] == ec[0] and cc[0] == fc[0])

    if kind in ("fraction", "probability"):
        try:
            af = _parse_frac(a)
            ef = _parse_frac(e)
            if af is not None and ef is not None:
                return af == ef
        except Exception:
            pass
        return _word_match(a, e)

    if kind in _WORD_KINDS:
        return _word_match(a, e)

    if kind == "prime_factorization":
        a_nums = sorted(int(x) for x in re.findall(r"\d+", a))
        e_nums = sorted(int(x) for x in re.findall(r"\d+", e))
        return a_nums == e_nums and bool(a_nums)

    # numeric kinds (algebra, code, modular, arithmetic, sequence, gcd_lcm, ...)
    a_num = re.sub(r"[^0-9-]", "", a)
    e_num = re.sub(r"[^0-9-]", "", e)
    if e_num and a_num == e_num:
        return True
    # fall back to word match for letter answers that slipped through
    return _word_match(a, e)


def _parse_frac(s):
    """Parse 'a/b' or 'a' or '0.5' to a Fraction (or None)."""
    from fractions import Fraction
    s = s.strip()
    if "/" in s:
        return Fraction(s)
    if s.replace(".", "", 1).isdigit():
        return Fraction(s)
    return None


def verify(agent_answer, game):
    """Return a grade dict for one agent. `game` is the dict from gen_question."""
    ans_text, conf = parse_answer(agent_answer)
    kind = game["kind"]
    if kind == "dilemma":
        a = _norm(ans_text)
        horn_hits = {}
        for label, kws in game.get("horns", []):
            horn_hits[label] = sum(1 for kw in kws if kw in a)
        escape_hits = sum(1 for kw in game.get("escape_keywords", []) if kw in a)
        # Escaped = the agent reached for a concept beyond the two offered horns.
        # (escape keywords are specific multi-word phrases like "save everyone",
        #  so a plain horn answer like "pull the lever" won't trigger them.)
        escaped = escape_hits > 0
        return {
            "answer": ans_text,
            "confidence": conf,
            "correct": None,
            "escaped": escaped,
            "horn_hits": horn_hits,
            "escape_hits": escape_hits,
        }
    correct = check_correct(ans_text, game["answer"], kind)
    return {
        "answer": ans_text,
        "confidence": conf,
        "correct": correct,
        "expected": game["answer"],
    }


def parse_move(text, options):
    """Return the index of the first `options` label found in text, else None."""
    t = _norm(text) if text else ""
    for i, opt in enumerate(options):
        if opt in t:
            return i
    return None


def grade_matrix_play(game, a_idx, b_idx):
    """Grade a simultaneous-move 2x2 game. a_idx/b_idx are row/col indices."""
    payoffs = game["payoffs"]
    rows, cols = game["rows"], game["cols"]
    rp, cp = payoffs[(a_idx, b_idx)]
    a_best = rp >= payoffs[(1 - a_idx, b_idx)][0]
    b_best = cp >= payoffs[(a_idx, 1 - b_idx)][1]
    ne = game["ne"]
    equilibrium = (a_idx, b_idx) == ne
    return {
        "row_move": rows[a_idx],
        "col_move": cols[b_idx],
        "payoff_row": rp,
        "payoff_col": cp,
        "a_best_response": a_best,
        "b_best_response": b_best,
        "equilibrium": equilibrium,
        "ne": f"{rows[ne[0]]}, {cols[ne[1]]}",
    }
