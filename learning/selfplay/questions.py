"""
Deterministic, verifiable game bank for self-play.

Every game is generated by MY code and its ground-truth answer is computed by
MY code — never by evaluating model output. The verifier only compares a
model's stated answer string against the known answer. No LLM is the judge.

Games come in one registry (GAME_TYPES, rotation order) and each returns
(question, answer, kind). Kinds carry an answer "shape" so the verifier can
compare appropriately: numeric, fraction, word, boolean, or matrix-cell.
"""

