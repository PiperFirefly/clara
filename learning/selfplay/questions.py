# ─────────────────────────── 17. matrix Nash equilibrium ───────────────────────────

def _pure_ne(payoffs):
    """Pure-strategy Nash equilibria of a 2x2 game. payoffs[(r,c)] = (row, col)."""
    nes = []
    for r in (0, 1):
        for c in (0, 1):
            rp, cp = payoffs[(r, c)]
            row_ok = rp >= payoffs[(1 - r, c)][0]
            col_ok = cp >= payoffs[(r, 1 - c)][1]
            if row_ok and col_ok:
                nes.append((r, c))
    return nes


def gen_matrix_nash():
    for _ in range(300):
        payoffs = {(r, c): (_r(0, 9), _r(0, 9)) for r in (0, 1) for c in (0, 1)}
        nes = _pure_ne(payoffs)
        if len(nes) == 1:
            r, c = nes[0]
            rows = ["Top", "Bottom"]
            cols = ["Left", "Right"]
            matrix = (
                "Payoff matrix (row player's payoff, column player's payoff):\n"
                f"            Left           Right\n"
                f"Top     {payoffs[(0, 0)]}   {payoffs[(0, 1)]}\n"
                f"Bottom  {payoffs[(1, 0)]}   {payoffs[(1, 1)]}\n"
            )
            ans = f"{rows[r]}, {cols[c]}"
            q = (matrix + "Which cell is the (unique) pure-strategy Nash equilibrium? "
                 "Answer e.g. 'Top, Left'.")
            return q, ans.lower(), "matrix_nash"
    # unreachable in practice; fall back to a known-unique game
    return gen_matrix_nash()


def gen_matrix_play():
    """A true adversarial game: A picks a row, B picks a column, simultaneously.

    Returns a full game dict (game_type='play') — no single 'expected' answer;
    the verifier scores best-responses and whether the joint move is the
    unique pure Nash equilibrium."""
    for _ in range(300):
        payoffs = {(r, c): (_r(0, 9), _r(0, 9)) for r in (0, 1) for c in (0, 1)}
        nes = _pure_ne(payoffs)
        if len(nes) == 1:
            matrix_text = (
                "Payoff matrix (row player's payoff, column player's payoff):\n"
                f"            Left           Right\n"
                f"Top     {payoffs[(0, 0)]}   {payoffs[(0, 1)]}\n"
                f"Bottom  {payoffs[(1, 0)]}   {payoffs[(1, 1)]}\n"
            )
            return {
                "kind": "matrix_play",
                "game_type": "play",
                "pattern": "play",
                "question": matrix_text,
                "matrix_text": matrix_text,
                "payoffs": payoffs,
                "ne": nes[0],
                "rows": ["Top", "Bottom"],
                "cols": ["Left", "Right"],
                "answer": None,
            }
    return gen_matrix_play()


